	<h1>Privacy Policy</h1>
	<p>Headways, by transbay.dev. Last updated October 2, 2026.</p>

	<h2>Location</h2>
	<p>If you allow it, Headways uses your location to show nearby stops and vehicles and to plan trips. When you plan a trip, the start and end points are sent to our server to find routes. We do not keep a history of where you have been or sell your location.</p>

	<h2>Account</h2>
	<p>You can sign in with Apple through a Transbay account. We store your account ID, username, and the data you choose to sync, such as past journeys, pinned lines, and settings. You can delete your account and this data at any time from the app.</p>

	<h2>Live Activities and notifications</h2>
	<p>When you start a journey with Go, the app sends our server the journey plan and a push token so it can update your Live Activity and alert you at your stop. These are discarded after the journey.</p>

	<h2>Server requests</h2>
	<p>Our server sees your IP address and the stops, routes, and vehicles you ask about, which is needed to answer requests. We do not use analytics, advertising, or tracking, and we do not sell or share your data.</p>

	<h2>Children</h2>
	<p>Headways is not directed at children under 13.</p>

	<h2>Changes</h2>
	<p>If this policy changes, the date above will change with it.</p>

